/**
 * Сигнал «инфраструктура готова» — локализация загружена, навбар отрисован.
 *
 * Почему не хватило обычного document.addEventListener('lms:ready'):
 * ES-модули грузятся асинхронно, и порядок их выполнения не гарантирован.
 * app.js мог успеть отправить событие раньше, чем скрипт страницы догрузил
 * свои импорты и подписался — тогда обработчик не вызывался вообще, и страница
 * оставалась пустой. Проявлялось это плавающе: на быстрых страницах всё
 * работало, на страницах с длинной цепочкой импортов — нет.
 *
 * Здесь состояние запоминается: подписка ПОСЛЕ готовности выполняется сразу.
 */

let isReady = false;
const waiting = [];

/** Вызывается один раз из app.js, когда инициализация завершена. */
export function markReady() {
    if (isReady) {
        return;
    }

    isReady = true;

    // splice(0) забирает и очищает очередь: каждый обработчик выполнится один раз,
    // даже если внутри него кто-то подпишется снова.
    waiting.splice(0).forEach((callback) => run(callback));

    // Событие оставлено для инлайновых скриптов на странице, которым
    // неудобно импортировать модуль (например, демо на styleguide.html).
    document.dispatchEvent(new CustomEvent('lms:ready'));
}

/**
 * Выполнить, когда инфраструктура готова.
 * Если она уже готова — выполнить немедленно.
 */
export function onReady(callback) {
    if (isReady) {
        run(callback);
        return;
    }

    waiting.push(callback);
}

/** Ошибка в одном обработчике не должна ломать остальные. */
function run(callback) {
    try {
        const result = callback();

        if (result && typeof result.catch === 'function') {
            result.catch((error) => console.error('Ошибка инициализации страницы:', error));
        }
    } catch (error) {
        console.error('Ошибка инициализации страницы:', error);
    }
}
